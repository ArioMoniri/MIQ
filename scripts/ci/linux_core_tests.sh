#!/usr/bin/env bash
# Builds and tests MIQCore (plus the `miq` CLI) on Linux, so contributors without
# a Mac — and the `linux-core` CI job — can run the core test suite.
#
# MIQCore is pure Swift + zlib, but it touches a few Apple-only modules (os.log,
# the BSD iopolicy/statfs calls). This script copies the package sources into a
# scratch package, swaps those for small shims, and runs `swift build` + `swift
# test` there. The checkout itself is never modified.
#
# Usage:
#   scripts/ci/linux_core_tests.sh [swift test args…]
#     e.g. scripts/ci/linux_core_tests.sh --filter PNGEncoderTests
#
# Environment:
#   MIQ_SRC       repository root (default: this script's ../..)
#   MIQ_WORK      scratch package dir (default: $MIQ_SRC/.build/linux-harness)
#   SWIFT         swift executable (default: `swift` on PATH)
#
# Requirements: Swift 6.x toolchain, zlib headers (zlib1g-dev), python3.
#
# Differences from a macOS `swift test`:
#   - PerformanceBaselineTests.swift is excluded (it imports Apple's Compression).
#   - VolumeLocation.isLocal is stubbed to `true` (no BSD statfs/MNT_LOCAL).
#   - os.log Logger calls compile to no-ops.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="${MIQ_SRC:-$(cd "$SCRIPT_DIR/../.." && pwd)}"
W="${MIQ_WORK:-$SRC/.build/linux-harness}"
SWIFT="${SWIFT:-swift}"

if [[ "$(uname -s)" == "Darwin" ]]; then
  echo "note: on macOS just run 'swift test' — this harness is for Linux." >&2
fi
[[ -f /usr/include/zlib.h ]] || { echo "error: /usr/include/zlib.h missing — install zlib1g-dev" >&2; exit 1; }
command -v python3 >/dev/null || { echo "error: python3 is required" >&2; exit 1; }

rm -rf "$W/Sources" "$W/Tests"
mkdir -p "$W/Sources/zlib" "$W/Sources/MIQCore" "$W/Sources/miq" "$W/Tests"
cp -R "$SRC/Sources/MIQCore/." "$W/Sources/MIQCore/"
cp -R "$SRC/Sources/miq/." "$W/Sources/miq/"
cp -R "$SRC/Tests/." "$W/Tests/"
rm -f "$W/Tests/MIQCoreTests/PerformanceBaselineTests.swift"  # uses Apple Compression

cat > "$W/Sources/zlib/module.modulemap" <<'M'
module zlib [system] { header "/usr/include/zlib.h" link "z" export * }
M

# Comment out `import os.log` / `import os`; the shims below provide the API.
grep -rlE "^import os(\.log)?$" "$W/Sources" "$W/Tests" | xargs -r sed -i \
  -e 's/^import os.log$/\/\/ import os.log (shimmed)/' \
  -e 's/^import os$/\/\/ import os (shimmed)/'

cat > "$W/Sources/MIQCore/_LinuxShims.swift" <<'S'
#if os(Linux)
import Foundation
public enum OSLogPrivacy { case `public`, `private`, sensitive, auto; static func `private`(mask: Int) -> OSLogPrivacy { .private } }
public struct OSLogMessage: ExpressibleByStringInterpolation, ExpressibleByStringLiteral {
  public init(stringLiteral: String) {}
  public init(stringInterpolation: Interp) {}
  public struct Interp: StringInterpolationProtocol {
    public init(literalCapacity: Int, interpolationCount: Int) {}
    public mutating func appendLiteral(_ s: String) {}
    public mutating func appendInterpolation<T>(_ v: @autoclosure () -> T, privacy: OSLogPrivacy = .auto) {}
    public mutating func appendInterpolation<T>(_ v: @autoclosure () -> T, format: Any? = nil, privacy: OSLogPrivacy = .auto) {}
  }
}
public struct Logger: Sendable {
  public init(subsystem: String, category: String) {}
  public init() {}
  public func notice(_ m: OSLogMessage) {} ; public func error(_ m: OSLogMessage) {}
  public func debug(_ m: OSLogMessage) {} ; public func info(_ m: OSLogMessage) {}
  public func warning(_ m: OSLogMessage) {} ; public func fault(_ m: OSLogMessage) {}
  public func log(_ m: OSLogMessage) {}
}
public let IOPOL_TYPE_DISK: Int32 = 0; public let IOPOL_SCOPE_THREAD: Int32 = 1
public let IOPOL_THROTTLE: Int32 = 3; public let IOPOL_DEFAULT: Int32 = 0
public func getiopolicy_np(_ a: Int32, _ b: Int32) -> Int32 { 0 }
@discardableResult public func setiopolicy_np(_ a: Int32, _ b: Int32, _ c: Int32) -> Int32 { 0 }
#endif
S

# VolumeLocation: Linux has no BSD statfs/MNT_LOCAL; stub isLocal's body to "local".
python3 - "$W/Sources/MIQCore/VolumeLocation.swift" <<'PY'
import re, sys
p = sys.argv[1]
s = open(p).read()
s2 = re.sub(r'(public static func isLocal\(_ url: URL\) -> Bool \{)\n.*?\n    \}\n',
            r'\1\n        return true\n    }\n', s, count=1, flags=re.S)
if s2 == s:
    sys.exit("error: could not stub VolumeLocation.isLocal — update scripts/ci/linux_core_tests.sh")
open(p, 'w').write(s2)
PY

cat > "$W/Package.swift" <<'P'
// swift-tools-version: 6.0
// Generated by scripts/ci/linux_core_tests.sh — mirrors the repo's Package.swift
// plus an explicit zlib system module (macOS gets it from the SDK).
import PackageDescription
let package = Package(name: "MIQ", platforms: [.macOS(.v14)],
  targets: [
    .systemLibrary(name: "zlib", path: "Sources/zlib"),
    .target(name: "MIQCore", dependencies: ["zlib"]),
    .executableTarget(name: "miq", dependencies: ["MIQCore"]),
    .testTarget(name: "MIQCoreTests", dependencies: ["MIQCore", "zlib"]),
    .testTarget(name: "MIQCLITests", dependencies: ["miq", "MIQCore"])
  ])
P

cd "$W"
echo "==> swift build --build-tests ($W)"
if ! "$SWIFT" build --build-tests >"$W/build.log" 2>&1; then
  grep -E "error:" "$W/build.log" | sort -u | head -60 || true
  echo "---- last 40 lines of $W/build.log ----"
  tail -40 "$W/build.log"
  exit 1
fi
grep -E "warning: unre" "$W/build.log" || true
echo "==> swift test"
"$SWIFT" test --skip-build "$@"
